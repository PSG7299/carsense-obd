String describeDtc(String code) {
  final known = dtcDescriptions[code];
  if (known != null) return known;
  return _rangeDescription(code);
}

String _rangeDescription(String code) {
  final letter = code[0];
  // P1/P3, and B/C/U 1–2 are manufacturer-controlled ranges (SAE J2012).
  final mfr = code[1] == '1' || code[1] == '3' || (letter != 'P' && code[1] == '2');
  final system = switch (letter) {
    'P' => 'Powertrain',
    'C' => 'Chassis (ABS / steering / suspension)',
    'B' => 'Body (airbags, lights, comfort)',
    'U' => 'Network / module communication',
    _ => 'Unknown',
  };
  if (letter == 'P') {
    final group = switch (code[2]) {
      '0' || '1' || '2' => 'fuel and air metering',
      '3' => 'ignition system or misfire',
      '4' => 'auxiliary emission controls',
      '5' => 'vehicle speed, idle control or auxiliary inputs',
      '6' => 'computer and output circuits',
      '7' || '8' || '9' => 'transmission',
      'A' || 'B' || 'C' => 'hybrid propulsion',
      _ => 'powertrain',
    };
    return '${mfr ? 'Manufacturer-specific' : 'Generic'} powertrain fault – $group';
  }
  return '${mfr ? 'Manufacturer-specific' : 'Generic'} $system fault';
}

Severity dtcSeverity(String code) {
  if (RegExp(r'^P030[0-9]$').hasMatch(code)) return Severity.high; // misfire – can damage catalyst
  if (const {'P0217', 'P0219', 'P0234', 'P0335', 'P0520', 'P0562', 'P0563', 'P0601', 'P0606', 'U0100'}
      .contains(code)) {
    return Severity.high;
  }
  if (RegExp(r'^P04[4-5]').hasMatch(code) || code == 'P0603' || code == 'P0650') {
    return Severity.low; // EVAP leaks, memory reset, lamp circuit
  }
  return Severity.medium;
}
