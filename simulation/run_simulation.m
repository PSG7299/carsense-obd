function results = run_simulation(make_plots)
%RUN_SIMULATION Simulate every scenario on both cars, diagnose each one,
%   export replay files for the app and (optionally) save plots.
%
%   run_simulation          % replays + plots
%   run_simulation(false)   % replays only (faster)
%
%   Outputs
%     ../assets/simulations/<car>_<scenario>.json  replay files for the app
%     output/plots/<car>_<scenario>.png            overview plots
%     output/summary.md                            results table

if nargin < 1, make_plots = true; end
here = fileparts(mfilename('fullpath'));
replay_dir = fullfile(here, '..', 'assets', 'simulations');
plot_dir = fullfile(here, 'output', 'plots');
if ~exist(replay_dir, 'dir'), mkdir(replay_dir); end
if make_plots && ~exist(plot_dir, 'dir'), mkdir(plot_dir); end

[~, names] = carsim_scenarios();
cars = {'nexon', 'swift'};
results = struct('car', {}, 'scenario', {}, 'score', {}, 'overall', {}, ...
                 'stored', {}, 'pending', {}, 'battery', {}, 'problems', {});
md = {'| Car | Scenario | Score | Overall | Stored DTCs | Pending | Battery test | Sensors flagged |', ...
      '|---|---|---|---|---|---|---|---|'};

for c = 1:numel(cars)
  for i = 1:numel(names)
    sim  = carsim_simulate(cars{c}, names{i}, 1);
    r    = carsim_replies(sim);
    data = carsim_read(r);
    res  = carsim_diagnose(data, sim.profile);
    batt = carsim_battery_eval(data.battery_trace);
    base = sprintf('%s_%s', cars{c}, names{i});
    carsim_export_replay(sim, r, res, batt, fullfile(replay_dir, [base '.json']));
    if make_plots
      carsim_plot(sim, data, res, batt, fullfile(plot_dir, [base '.png']));
    end

    f = fieldnames(res.status);
    flagged = {};
    for k = 1:numel(f)
      st = res.status.(f{k});
      if any(strcmp(st, {'warn', 'fail'})), flagged{end+1} = sprintf('%s (%s)', f{k}, st); end %#ok<AGROW>
    end
    results(end+1) = struct('car', cars{c}, 'scenario', names{i}, 'score', res.score, ...
        'overall', res.overall, 'stored', {sim.dtc_stored}, 'pending', {sim.dtc_pending}, ...
        'battery', batt.status, 'problems', {flagged}); %#ok<AGROW>
    md{end+1} = sprintf('| %s | %s | %d | %s | %s | %s | %s | %s |', sim.profile.name, ...
        strrep(names{i}, '_', ' '), res.score, res.overall, j(sim.dtc_stored), j(sim.dtc_pending), ...
        batt.status, j(flagged)); %#ok<AGROW>
    fprintf('%-6s %-17s score %3d %-4s  stored [%s]  pending [%s]  battery %-4s  flagged: %s\n', ...
        cars{c}, names{i}, res.score, res.overall, j(sim.dtc_stored), j(sim.dtc_pending), batt.status, j(flagged));
  end
end

out_dir = fullfile(here, 'output');
if ~exist(out_dir, 'dir'), mkdir(out_dir); end
fid = fopen(fullfile(out_dir, 'summary.md'), 'w');
fprintf(fid, '# Simulation results\n\nGenerated by `run_simulation.m` (seed 1).\n\n%s\n', strjoin(md, sprintf('\n')));
fclose(fid);
end

function s = j(c)
if isempty(c), s = '-'; else, s = strjoin(c, ', '); end
end
